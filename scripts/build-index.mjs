// Rebuilds assets/data/course-index.js: the list of pages and their sections (sidebar, progress, review, "Next" cards,
// command palette) and every numbered interview question (mock interview). Run it after adding or changing a lesson:
//   node scripts/build-index.mjs
// Pages: java/index.html (home), java/lessons/*.html in file-name order, then java/playground.html and java/practice.html. Paths are relative to the site root (ROOT in course.js). Each page's <body> carries
// data-page (key, e.g. l05), data-name ("Lesson 05 · OOP") and data-short ("L05").
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
// Two courses, two indexes: `node scripts/build-index.mjs` (Java: java/index.html + java/lessons/*.html + java/practice.html → assets/data/course-index.js) and
// `node scripts/build-index.mjs sql` (SQL: sql/index.html + sql/NN-*.html → assets/data/sql-index.js) and
// `node scripts/build-index.mjs spring` (the Spring Boot lab: spring/index.html → assets/data/spring-index.js) and
// `node scripts/build-index.mjs patterns` (Design Patterns: patterns/index.html + patterns/NN-*.html → assets/data/patterns-index.js).
const COURSE = ["sql", "spring", "patterns"].includes(process.argv[2]) ? process.argv[2] : "java";
const files = COURSE === "spring" ? ["spring/index.html"] : COURSE === "sql" || COURSE === "patterns"
  ? [COURSE + "/index.html", ...fs.readdirSync(path.join(ROOT, COURSE)).filter(f => /^\d\d-.*\.html$/.test(f)).sort().map(f => COURSE + "/" + f)]
  : ["java/index.html", ...fs.readdirSync(path.join(ROOT, "java/lessons")).filter(f => f.endsWith(".html")).sort().map(f => "java/lessons/" + f), "java/playground.html", "java/practice.html"].filter(f => fs.existsSync(path.join(ROOT, f)));
const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'", nbsp: " " };
const text = h => h.replace(/<[^>]+>/g, "").replace(/&(\w+|#\d+);/g, (m, e) => ENT[e] ?? m).replace(/\s+/g, " ").trim();

const pages = [], qa = [];
for (const file of files) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const attr = n => (html.match(new RegExp("<body[^>]*\\sdata-" + n + '="([^"]*)"')) || [])[1] || "";
  const key = attr("page");
  if (!key) throw new Error(file + ": <body> has no data-page");
  const band = (html.match(/<div class="band" id="([^"]+)"/) || [])[1] || "";
  const sections = [];
  const parts = html.split(/(?=<section id=")/).slice(1);
  for (const part of parts) {
    const id = part.match(/^<section id="([^"]+)"/)[1];
    const m = part.match(/<span class="num">([^<]*)<\/span>\s*<h2(?:\s[^>]*)?>([\s\S]*?)<\/h2>/);
    if (!m) continue;
    const st = text(m[2]);
    sections.push({ id, n: text(m[1]), t: st });
    const body = part.slice(0, part.indexOf("</section>"));
    for (const d of body.matchAll(/<details class="d"><summary><span class="q">([^<]+)<\/span>([\s\S]*?)<\/summary><div class="b">([\s\S]*?)<\/div><\/details>/g))
      qa.push({ k: id + ":" + d[1].trim(), l: attr("short"), sec: id, st, q: d[2].trim(), a: d[3] });
  }
  pages.push({ key, file, name: attr("name"), short: attr("short"), band, sections });
}

const out = "/* generated by scripts/build-index.mjs, do not edit by hand */\nwindow.COURSE=" + JSON.stringify({ pages, qa }) + ";\n";
fs.writeFileSync(path.join(ROOT, ({ sql: "assets/data/sql-index.js", spring: "assets/data/spring-index.js", patterns: "assets/data/patterns-index.js" })[COURSE] || "assets/data/course-index.js"), out);
console.log(pages.map(p => p.short + ": " + p.sections.length).join(", ") + " · " + qa.length + " interview questions");
