// Rebuilds assets/course-index.js: the list of pages and their sections (sidebar, progress, review, "Next" cards,
// command palette) and every numbered interview question (mock interview). Run it after adding or changing a lesson:
//   node scripts/build-index.mjs
// Pages: Java.html (home), lessons/*.html in file-name order, then practice.html. Each page's <body> carries
// data-page (key, e.g. l05), data-name ("Lesson 05 · OOP") and data-short ("L05").
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const files = ["Java.html", ...fs.readdirSync(path.join(ROOT, "lessons")).filter(f => f.endsWith(".html")).sort().map(f => "lessons/" + f), "practice.html"];
const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'", nbsp: " " };
const text = h => h.replace(/<[^>]+>/g, "").replace(/&(\w+|#\d+);/g, (m, e) => ENT[e] ?? m).replace(/\s+/g, " ").trim();

const pages = [], qa = [];
for (const file of files) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const attr = n => (html.match(new RegExp("<body[^>]*\\sdata-" + n + '="([^"]*)"')) || [])[1] || "";
  const key = attr("page");
  if (!key) throw new Error(file + ": <body> has no data-page");
  const band = (html.match(/<div class="band" id="([^"]+)"/) || [])[1] || "";
  const sections = [];
  const parts = html.split(/(?=<section id=")/).slice(1);
  for (const part of parts) {
    const id = part.match(/^<section id="([^"]+)"/)[1];
    const m = part.match(/<span class="num">([^<]*)<\/span>\s*<h2>([\s\S]*?)<\/h2>/);
    if (!m) continue;
    const st = text(m[2]);
    sections.push({ id, n: text(m[1]), t: st });
    const body = part.slice(0, part.indexOf("</section>"));
    for (const d of body.matchAll(/<details class="d"><summary><span class="q">([^<]+)<\/span>([\s\S]*?)<\/summary><div class="b">([\s\S]*?)<\/div><\/details>/g))
      qa.push({ k: id + ":" + d[1].trim(), l: attr("short"), sec: id, st, q: d[2].trim(), a: d[3] });
  }
  pages.push({ key, file, name: attr("name"), short: attr("short"), band, sections });
}

const out = "/* generated by scripts/build-index.mjs, do not edit by hand */\nwindow.COURSE=" + JSON.stringify({ pages, qa }) + ";\n";
fs.writeFileSync(path.join(ROOT, "assets/course-index.js"), out);
console.log(pages.map(p => p.short + ": " + p.sections.length).join(", ") + " · " + qa.length + " interview questions");
